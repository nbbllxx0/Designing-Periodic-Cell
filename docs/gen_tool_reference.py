"""Generate docs/tool_contract.md from the live tool contract (amm.tools.contract), so the reference is never copied
by hand.

    python docs/gen_tool_reference.py           # (re)write docs/tool_contract.md
    python docs/gen_tool_reference.py --check   # exit 1 if docs/tool_contract.md is out of date (used by CI)

The same contract is frozen per schema version in results/software/contract_amm-tools-{1,2,3}.json
(scripts/software/write_contract.py); the generated page says whether the live contract equals the file of its
schema version (B9, 2026-11-08: the page follows amm.tools.SCHEMA_VERSION instead of naming amm-tools/2).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "tool_contract.md"


def frozen_path(schema: str) -> Path:
    return ROOT / "results" / "software" / f"contract_{schema.replace('/', '-')}.json"

GROUPS = [("Specification", ["set_material", "set_constraints", "set_target", "set_source", "undo", "get_session"]),
          ("Checks and questions", ["check_bounds", "ask_clarification"]),
          ("Design (search tier)", ["list_families", "atlas_suggest", "evaluate", "search"]),
          ("Acceptance tier", ["certify", "as_built"]),
          ("Manufacturing and export", ["screen_manufacturing", "export"]),
          ("Final answer", ["submit"])]


def _type(s: dict, defs: dict) -> str:
    if "$ref" in s:
        name = s["$ref"].split("/")[-1]
        return f"[{name}](#type-{name.lower()})"
    if "anyOf" in s:
        parts = [_type(x, defs) for x in s["anyOf"]]
        return " or ".join(p for p in parts if p != "null") + (" or null" if "null" in parts else "")
    if "const" in s:
        return f'"{s["const"]}"'
    if "enum" in s:
        return " \\| ".join(f'"{v}"' for v in s["enum"])
    t = s.get("type")
    if t == "array":
        return f"list of {_type(s.get('items', {}), defs)}"
    if t == "object" and "additionalProperties" in s and isinstance(s["additionalProperties"], dict):
        return f"dict of {_type(s['additionalProperties'], defs)}"
    return {"number": "float", "integer": "int", "string": "str", "boolean": "bool", "null": "null",
            "object": "object"}.get(t, "any")


def _default(name: str, s: dict, required: list) -> str:
    if name in required:
        return "required"
    if "default" in s:
        return "`" + json.dumps(s["default"]) + "`"
    return ""


def _desc(s: dict) -> str:
    d = s.get("description", "")
    for x in s.get("anyOf", []):
        d = d or x.get("description", "")
    return d.replace("\n", " ").replace("|", "\\|")


def render(c: dict) -> str:
    tools = c["tools"]
    defs: dict = {}
    for t in tools.values():
        defs.update(t["args"].get("$defs", {}))
    L = [f"# Tool contract (`{c['schema_version']}`)", "",
         "<!-- GENERATED by docs/gen_tool_reference.py from amm.tools.contract(); do not edit by hand. -->", "",
         f"Schema version: `{c['schema_version']}`. Outcome schema: `{c['outcome_schema']}`. "
         f"{len(tools)} tools. Every tool is a method of `amm.tools.Session`; call it as "
         "`session.call(name, args)`, which validates the arguments (unknown keys are rejected), runs the tool, "
         "appends one record to `session.jsonl` (when the session has a directory) and returns "
         "`{ok, seq, state_hash, schema_version, result | error}`. The MCP server (`python -m amm.mcp_server`) "
         "exposes the same tools with the same descriptions.", ""]
    L += [f"The frozen copy of this contract is `results/software/{frozen_path(c['schema_version']).name}` "
          "(`scripts/software/write_contract.py`); `python docs/gen_tool_reference.py` reports whether the live "
          "contract still equals it.", ""]
    L += ["Profiles: **C** is the full system; **B** is the ablation arm of the benchmark (no `check_bounds`, no "
          "certificates, no as-built check). A tool marked *mutates* changes the specification and can be undone.",
          "", "## Index", "", "| Tool | Profiles | Since | Mutates |", "|---|---|---|---|"]
    for _, names in GROUPS:
        for n in names:
            t = tools[n]
            L.append(f"| [`{n}`](#{n}) | {', '.join(t['profiles'])} | {t['since']} | {'yes' if t['mutates'] else ''} |")
    missing = [n for n in tools if not any(n in g for _, g in GROUPS)]
    for n in missing:
        t = tools[n]
        L.append(f"| [`{n}`](#{n}) | {', '.join(t['profiles'])} | {t['since']} | {'yes' if t['mutates'] else ''} |")
    L.append("")
    for title, names in GROUPS + ([("Other", missing)] if missing else []):
        L += [f"## {title}", ""]
        for n in names:
            t = tools[n]
            a = t["args"]
            props, req = a.get("properties", {}), a.get("required", [])
            L += [f"### `{n}`", "", t["doc"].replace("\n", " "), "",
                  f"Profiles {', '.join(t['profiles'])}; since `{t['since']}`"
                  + ("; mutates the specification" if t["mutates"] else "")
                  + "".join(f"; argument `{k}` since `{v}`" for k, v in (t.get("arg_since") or {}).items()) + "."]
            if t["result_schemas"]:
                L.append("Result schemas: " + ", ".join(f"`{k or 'result'}` = `{v}`"
                                                       for k, v in t["result_schemas"].items()) + ".")
            L.append("")
            if props:
                L += ["| Argument | Type | Default | Description |", "|---|---|---|---|"]
                for p, s in props.items():
                    L.append(f"| `{p}` | {_type(s, defs)} | {_default(p, s, req)} | {_desc(s)} |")
            else:
                L.append("No arguments.")
            L.append("")
    L += ["## Argument types", ""]
    for name, s in sorted(defs.items()):
        L += [f"### Type `{name}`", "", s.get("description", "").replace("\n", " "), "",
              "| Field | Type | Required | Description |", "|---|---|---|---|"]
        for p, ps in s.get("properties", {}).items():
            L.append(f"| `{p}` | {_type(ps, defs)} | {'yes' if p in s.get('required', []) else ''} | {_desc(ps)} |")
        L.append("")
    L += ["## Outcomes", "", "| Outcome | Title | Definition |", "|---|---|---|"]
    for k, v in c["outcomes"].items():
        L.append(f"| `{k}` | {v['title']} | {v['definition']} |")
    L += ["", "## Evidence records and the refusal rule", "",
          f"Applied in profile(s) {', '.join(c['refusal_rule_profiles'])}. `submit(decision=\"refuse\", verdict=V)` "
          "must cite (or hold) an evidence record of one of these kinds for the current specification:", "",
          "| Verdict | Accepted evidence kinds |", "|---|---|"]
    for v, kinds in c["refusal_rule"].items():
        L.append(f"| `{v}` | {', '.join(f'`{k}`' for k in kinds)} |")
    L += ["", "| Evidence kind | Supports outcome |", "|---|---|"]
    for k, v in c["evidence_kinds"].items():
        L.append(f"| `{k}` | `{v}` |")
    if c.get("added_in_schema_2"):
        L += ["", "## Fields added in schema 2", "",
              "Schema 2 only adds to schema 1; a version-1 log replays against the version-1 projection.", ""]
        for k, v in c["added_in_schema_2"].items():
            L.append(f"- `{k}`: {json.dumps(v)}")
    if c.get("added_in_schema_3"):
        L += ["", "## Added in schema 3", "",
              "Schema 3 only adds the optional `bands` argument of `evaluate` (default false: the result is the "
              "schema-2 result) and, when it is true, a `bands` field per design (f* per k-point and band on the "
              "k-path, the k-points over pi, the path labels, `n_bloch`, `n_bands` and, with material and cell size, "
              "`hz_per_f_star`). A version-2 log replays in a version-2 session, which does not accept the argument.",
              ""]
        for k, v in c["added_in_schema_3"].items():
            L.append(f"- `{k}`: {json.dumps(v)}")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    sys.path.insert(0, str(ROOT))
    import amm  # noqa: F401
    from amm import tools
    c = tools.contract(tools.SCHEMA_VERSION)
    frozen_same = None
    frozen = frozen_path(c["schema_version"])
    if frozen.exists():
        frozen_same = json.loads(frozen.read_text(encoding="utf-8")) == json.loads(json.dumps(c, sort_keys=True))
    text = render(c)
    if a.check:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur != text:
            print(f"{OUT} is out of date: run python docs/gen_tool_reference.py")
            return 1
        print(f"{OUT} is up to date ({len(c['tools'])} tools; frozen copy identical: {frozen_same})")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(c['tools'])} tools, frozen copy identical: {frozen_same})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
